"""
Customer Success FTE — Channel Response Formatter
====================================================
Phase 2: Specialization

Formats agent responses appropriately for each communication channel.
Handles greeting, signature, length limits, and style differences.
"""

from enum import Enum
from typing import Optional


class Channel(str, Enum):
    EMAIL = "email"
    WHATSAPP = "whatsapp"
    WEB_FORM = "web_form"


# Channel-specific configuration
CHANNEL_CONFIGS = {
    Channel.EMAIL: {
        'max_length': 2000,
        'style': 'formal',
        'requires_greeting': True,
        'requires_signature': True,
        'emoji_allowed': False,
        'greeting_template': "Dear {name},",
        'signature_template': (
            "\n\nIf you have any further questions, please don't hesitate to "
            "reply to this email.\n\n"
            "Best regards,\n"
            "TechCorp AI Support Team\n"
            "---\n"
            "Ticket Reference: {ticket_id}\n"
            "This response was generated by our AI assistant. "
            "For complex issues, you can request human support."
        ),
    },
    Channel.WHATSAPP: {
        'max_length': 1600,
        'preferred_length': 300,
        'style': 'casual',
        'requires_greeting': True,
        'requires_signature': False,
        'emoji_allowed': True,
        'greeting_template': "Hi {name}! ",
        'signature_template': (
            "\n\nReply for more help or type 'human' for live support. 😊"
        ),
    },
    Channel.WEB_FORM: {
        'max_length': 1000,
        'style': 'semi_formal',
        'requires_greeting': False,
        'requires_signature': True,
        'emoji_allowed': False,
        'greeting_template': "",
        'signature_template': (
            "\n\n---\n"
            "Need more help? Reply to this message or visit our support portal."
        ),
    },
}


def format_for_channel(response_text: str, channel: str,
                       ticket_id: str = "", customer_name: str = "") -> str:
    """Format response appropriately for the target channel.

    Args:
        response_text: The core response content
        channel: Target channel (email/whatsapp/web_form)
        ticket_id: Ticket reference for signature
        customer_name: Customer name for greeting

    Returns:
        Formatted response string
    """
    try:
        channel_enum = Channel(channel) if isinstance(channel, str) else channel
    except ValueError:
        channel_enum = Channel.WEB_FORM
    config = CHANNEL_CONFIGS.get(channel_enum, CHANNEL_CONFIGS[Channel.WEB_FORM])

    # Build greeting
    greeting = ""
    if config['requires_greeting']:
        name = customer_name if customer_name else "Customer"
        greeting = config['greeting_template'].format(name=name)

    # Build signature
    signature = ""
    if config['requires_signature']:
        signature = config['signature_template'].format(ticket_id=ticket_id)

    # Remove emojis if not allowed
    if not config['emoji_allowed']:
        response_text = _remove_emojis(response_text)

    # Assemble full response
    parts = []
    if greeting:
        parts.append(greeting)
    parts.append(response_text)
    if signature:
        parts.append(signature)

    full_response = "\n\n".join(parts)

    # Truncate if exceeds max length
    max_length = config['max_length']
    if len(full_response) > max_length:
        full_response = full_response[:max_length - 3] + "..."

    return full_response


def _remove_emojis(text: str) -> str:
    """Remove emoji characters from text."""
    import re
    # Emoji Unicode ranges
    emoji_pattern = re.compile(
        "["
        "\U0001F600-\U0001F64F"  # emoticons
        "\U0001F300-\U0001F5FF"  # symbols & pictographs
        "\U0001F680-\U0001F6FF"  # transport & map symbols
        "\U0001F1E0-\U0001F1FF"  # flags
        "\U00002702-\U000027B0"
        "\U000024C2-\U0001F251"
        "\U0001f926-\U0001f937"
        "\U00010000-\U0010ffff"
        "\u2640-\u2642"
        "\u2600-\u2B55"
        "\u200d"
        "\u23cf"
        "\u23e9"
        "\u231a"
        "\ufe0f"
        "\u3030"
        "\u303d"
        "\u2b50"
        "\u2b55"
        "]+",
        flags=re.UNICODE
    )
    return emoji_pattern.sub('', text).strip()


def truncate_for_channel(response_text: str, channel: str) -> str:
    """Truncate response to fit channel limits without cutting mid-sentence."""
    try:
        channel_enum = Channel(channel) if isinstance(channel, str) else channel
    except ValueError:
        channel_enum = Channel.WEB_FORM
    config = CHANNEL_CONFIGS.get(channel_enum, CHANNEL_CONFIGS[Channel.WEB_FORM])
    max_length = config.get('preferred_length', config['max_length'])

    if len(response_text) <= max_length:
        return response_text

    # Find a good break point
    truncated = response_text[:max_length]
    break_point = truncated.rfind('. ')
    if break_point == -1:
        break_point = truncated.rfind('! ')
    if break_point == -1:
        break_point = truncated.rfind('? ')
    if break_point == -1:
        break_point = truncated.rfind(' ', 0, max_length)
    if break_point == -1:
        break_point = max_length

    return response_text[:break_point + 1].strip() + "..."
